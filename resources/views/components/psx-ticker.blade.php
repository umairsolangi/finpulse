<script>
    function handlePsxTickerClick(symbol) {
        // Dispatch event for any active stock listeners
        window.dispatchEvent(new CustomEvent('select-psx-stock', { detail: symbol }));

        // Smoothly scroll down to the stock search / chart section
        var targetSection = document.getElementById('stock-search') || document.getElementById('stock-chart');
        if (targetSection) {
            targetSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
        }
    }
</script>
